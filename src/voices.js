// ==================== 辅助函数 ====================

export function buildReverseIndex(voices) {
  const index = {};
  for (const [label, v] of Object.entries(voices)) {
    index[v.voice_name] = label;
  }
  return index;
}

export function resolveVoice(voice, voices, reverseIndex) {
  if (voices[voice]) return voices[voice].voice_name;
  if (reverseIndex[voice]) return voice;
  throw new Error(`未知音色: ${voice}。可用音色: ${Object.keys(voices).join(", ")}`);
}

export function resolveEmotion(voiceLabel, emotion, voices) {
  if (!emotion) return "general";
  const info = voices[voiceLabel];
  if (!info) return emotion;
  if (info.emotions[emotion]) return info.emotions[emotion];
  if (Object.values(info.emotions).includes(emotion)) return emotion;
  const available = Object.keys(info.emotions);
  throw new Error(
    `音色 ${voiceLabel} 不支持情感 ${emotion}。可用情感: ${available.length ? available.join(", ") : "无"}`
  );
}

export function getVoiceLabel(voice, voices, reverseIndex) {
  if (voices[voice]) return voice;
  return reverseIndex[voice] || null;
}
